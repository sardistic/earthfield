// Regenerates worker/assets.js from assets/. Run after changing any icon or image:
//   node scripts/embed-assets.mjs
import {readFile,writeFile} from 'node:fs/promises';
const files={
 '/favicon.svg':['assets/favicon.svg','image/svg+xml'],
 '/favicon.ico':['assets/icon-32.png','image/png'],
 '/favicon-32.png':['assets/icon-32.png','image/png'],
 '/apple-touch-icon.png':['assets/icon-180.png','image/png'],
 '/icon-192.png':['assets/icon-192.png','image/png'],
 '/icon-512.png':['assets/icon-512.png','image/png'],
 '/og.jpg':['assets/og.jpg','image/jpeg'],
};
const out={};for(const[route,[file,type]]of Object.entries(files))out[route]=[type,(await readFile(file)).toString('base64')];
await writeFile('worker/assets.js','// Generated by scripts/embed-assets.mjs from assets/. Do not edit by hand.\nexport const ASSETS='+JSON.stringify(out)+';\n');
console.log('Embedded',Object.keys(out).length,'assets');
